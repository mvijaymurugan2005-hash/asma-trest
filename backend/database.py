def seed_trustee_photos(c):
    """One-time: attach the trustee photos + final names/roles. Runs once (flag in settings), so later edits made in Admin are never overwritten."""
    if c.execute("select 1 from settings where k='trustee_photos_v1'").fetchone():
        return
    os.makedirs(os.path.join(UP, "Trustees"), exist_ok=True)
    norm = lambda t: "".join(ch for ch in (t or "").lower() if ch.isalpha())
    rows = c.execute("select id,name from trustees").fetchall()
    for i, (key, fn, name, role) in enumerate(TRUSTEES):
        src = os.path.join(STATIC, "img", "trustees", fn)
        if not os.path.isfile(src):
            continue
        shutil.copyfile(src, os.path.join(UP, "Trustees", fn))
        rel = "Trustees/" + fn
        hit = next((r for r in rows if key in norm(r["name"])), None)
        if hit:
            c.execute(
                "update trustees set name=?,role=?,photo=?,sort=? where id=?",
                (name, role, rel, i, hit["id"]),
            )
        else:
            c.execute(
                "insert into trustees(name,role,bio,photo,sort) values(?,?,?,?,?)",
                (name, role, "", rel, i),
            )
    c.execute("insert into settings(k,v) values('trustee_photos_v1','1')")


