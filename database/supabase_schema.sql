-- ASMA Educational and Charitable Trust - Supabase (PostgreSQL) Schema
-- Paste and run this in Supabase Dashboard -> SQL Editor

-- 1. Site & Trust Settings (key-value store)
CREATE TABLE IF NOT EXISTS settings (
    k TEXT PRIMARY KEY,
    v TEXT
);

-- 2. Admin Accounts
CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE,
    pw TEXT
);

-- 3. Home Page Banners
CREATE TABLE IF NOT EXISTS banners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image TEXT,
    caption TEXT,
    sort INTEGER DEFAULT 0
);

-- 4. Trust Activities
CREATE TABLE IF NOT EXISTS activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT,
    description TEXT,
    image TEXT,
    sort INTEGER DEFAULT 0
);

-- 5. Projects ("full" is quoted because FULL is a reserved keyword in PostgreSQL)
CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT,
    category TEXT,
    short TEXT,
    "full" TEXT,
    main_image TEXT,
    images TEXT DEFAULT '[]',
    video TEXT,
    date TEXT,
    location TEXT,
    status TEXT DEFAULT 'Proposed',
    published INTEGER DEFAULT 0
);

-- 6. Gallery (Photos & Videos)
CREATE TABLE IF NOT EXISTS gallery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT,
    file TEXT,
    caption TEXT,
    activity TEXT,
    project TEXT
);

-- 7. Trustees
CREATE TABLE IF NOT EXISTS trustees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    role TEXT,
    bio TEXT,
    photo TEXT,
    sort INTEGER DEFAULT 0
);

-- 8. Contact Form Messages
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    email TEXT,
    phone TEXT,
    message TEXT,
    created TEXT,
    seen INTEGER DEFAULT 0
);

-- 9. Donations (Razorpay + historical UPI QR verification fields)
CREATE TABLE IF NOT EXISTS donations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ref TEXT UNIQUE,
    name TEXT,
    mobile TEXT,
    email TEXT,
    amount INTEGER,
    message TEXT,
    status TEXT,
    order_id TEXT,
    payment_id TEXT,
    created TEXT,
    address TEXT DEFAULT '',
    pan TEXT DEFAULT '',
    mode TEXT,
    method TEXT DEFAULT '',
    paid_at TEXT DEFAULT '',
    channel TEXT DEFAULT '',
    utr TEXT DEFAULT '',
    declared_amount INTEGER,
    screenshot TEXT DEFAULT '',
    shot_hash TEXT DEFAULT '',
    submitted_at TEXT DEFAULT '',
    verified_by TEXT DEFAULT '',
    verified_at TEXT DEFAULT '',
    verify_note TEXT DEFAULT '',
    reject_reason TEXT DEFAULT ''
);

-- 10. Donation Receipt Certificates
CREATE TABLE IF NOT EXISTS certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number TEXT UNIQUE,
    donation_id BIGINT UNIQUE,
    issued TEXT,
    emailed INTEGER DEFAULT 0,
    revoked INTEGER DEFAULT 0,
    seq INTEGER,
    fy TEXT,
    mode TEXT,
    email_error TEXT DEFAULT ''
);

-- 11. Certificate Number Aliases (Old -> New receipt number mapping)
CREATE TABLE IF NOT EXISTS cert_alias (
    old TEXT PRIMARY KEY,
    new_number TEXT
);

-- 12. 80G Tax Exemption Tracking (Form 10BD / Form 10BE)
CREATE TABLE IF NOT EXISTS g80 (
    donation_id BIGINT PRIMARY KEY,
    status TEXT DEFAULT 'review',
    arn TEXT DEFAULT '',
    filed_on TEXT DEFAULT '',
    filing_ref TEXT DEFAULT '',
    note TEXT DEFAULT '',
    form10be TEXT DEFAULT '',
    form10be_emailed TEXT DEFAULT '',
    updated TEXT
);

-- Indexes
CREATE UNIQUE INDEX IF NOT EXISTS ux_cert_seq
    ON certificates(fy, mode, seq);

CREATE UNIQUE INDEX IF NOT EXISTS ux_donation_utr
    ON donations(utr)
    WHERE utr <> '' AND status IN ('pending', 'paid');

